#!/usr/bin/env python3
"""Fetch the CC0 PBR texture sets used by the engine's built-in materials.

Sources: ambientCG (https://ambientcg.com), all assets released under CC0 1.0,
which allows commercial use and redistribution without attribution. The script
still writes assets/textures/CREDITS.md because crediting is cheap and polite.

Run:  python tools/fetch_textures.py [--size 512]

Output layout (consumed by TextureManager::load_texture_set):
    assets/textures/<Asset>/<Asset>_Color.jpg
    assets/textures/<Asset>/<Asset>_Normal.png
    assets/textures/<Asset>/<Asset>_Roughness.jpg

Only three maps are kept: albedo, OpenGL-convention normal and roughness. The
source zips also contain AO, displacement and DX normals, which the renderer
does not use; downscaling to 512 px keeps the repository small.
"""

from __future__ import annotations

import argparse
import io
import os
import shutil
import urllib.request
import zipfile

from PIL import Image

# Asset id -> (folder name, human label, engine purpose)
ASSETS = [
    ("Grass001", "Grass001", "Dense alpine turf (terrain layer 0 detail)"),
    ("Rock030", "Rock030", "Weathered granite cliff (terrain layer 1 detail)"),
    ("Ground080", "Ground080", "Wind-rippled coastal sand (terrain layer 2 detail)"),
    ("PavingStones131", "PavingStones131", "Flagstone plaza (terrain layer 3 detail)"),
    ("Wood066", "Wood066", "Timber planks (material preset 5 / built-in texture 3)"),
    ("Metal032", "Metal032", "Brushed steel (material preset 7 / built-in texture 2)"),
    ("Ground037", "Ground037", "Mossy soil (ground fallback / built-in texture 1)"),
]

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "assets", "textures")
CACHE_DIR = os.path.join(ROOT, "scratch", "texture_cache")

CREDITS_HEADER = """# Texture credits

Every texture in this folder comes from [ambientCG](https://ambientcg.com) and is
released under **CC0 1.0 Universal** (public domain dedication). Commercial use,
modification and redistribution are allowed without attribution; the list below
exists so the provenance stays traceable.

Generated by `tools/fetch_textures.py`; do not edit by hand.

| Folder | Source | License |
|:---|:---|:---|
"""


def download(url: str, dest: str) -> None:
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    print(f"  downloading {os.path.basename(dest)} ...", flush=True)
    req = urllib.request.Request(url, headers={"User-Agent": "GM3D/1.0 (texture fetch)"})
    with urllib.request.urlopen(req, timeout=120) as response, open(dest, "wb") as handle:
        shutil.copyfileobj(response, handle)


def pick_member(names: list[str], suffix: str) -> str | None:
    for name in names:
        base = os.path.basename(name).lower()
        if base.endswith(suffix.lower()):
            return name
    return None


def save_map(zip_file: zipfile.ZipFile, member: str, out_path: str, size: int, jpeg_quality: int | None) -> None:
    data = zip_file.read(member)
    image = Image.open(io.BytesIO(data))
    if image.mode not in ("RGB", "L"):
        image = image.convert("RGB")
    if image.width != size or image.height != size:
        image = image.resize((size, size), Image.LANCZOS)
    if jpeg_quality is None:
        image.save(out_path, format="PNG", optimize=True)
    else:
        if image.mode != "RGB":
            image = image.convert("RGB")
        image.save(out_path, format="JPEG", quality=jpeg_quality, optimize=True, progressive=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=512, help="target edge length in pixels")
    parser.add_argument("--force", action="store_true", help="re-extract even when the output exists")
    args = parser.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(CACHE_DIR, exist_ok=True)

    credits = [CREDITS_HEADER]
    for asset_id, folder, label in ASSETS:
        url = f"https://ambientcg.com/get?file={asset_id}_1K-JPG.zip"
        archive = os.path.join(CACHE_DIR, f"{asset_id}_1K-JPG.zip")
        print(f"[{asset_id}] {label}", flush=True)
        download(url, archive)

        target_dir = os.path.join(OUT_DIR, folder)
        os.makedirs(target_dir, exist_ok=True)

        with zipfile.ZipFile(archive) as zf:
            names = zf.namelist()
            color = pick_member(names, "_Color.jpg")
            normal = pick_member(names, "_NormalGL.jpg")
            roughness = pick_member(names, "_Roughness.jpg")
            if not color or not normal:
                print(f"  !! {asset_id}: unexpected archive layout, skipped")
                continue

            color_out = os.path.join(target_dir, f"{folder}_Color.jpg")
            normal_out = os.path.join(target_dir, f"{folder}_Normal.png")
            rough_out = os.path.join(target_dir, f"{folder}_Roughness.jpg")

            if args.force or not os.path.exists(color_out):
                save_map(zf, color, color_out, args.size, 92)
            if args.force or not os.path.exists(normal_out):
                save_map(zf, normal, normal_out, args.size, None)
            if roughness and (args.force or not os.path.exists(rough_out)):
                save_map(zf, roughness, rough_out, args.size, 92)

        credits.append(f"| `{folder}` | https://ambientcg.com/view?id={asset_id} | CC0 1.0 |\n")

    with open(os.path.join(OUT_DIR, "CREDITS.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.writelines(credits)

    total = 0
    for dirpath, _dirnames, filenames in os.walk(OUT_DIR):
        for name in filenames:
            total += os.path.getsize(os.path.join(dirpath, name))
    print(f"Done. {len(ASSETS)} sets, {total / (1024 * 1024):.1f} MB total in assets/textures")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
